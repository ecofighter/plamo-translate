#!/usr/bin/env python3
"""Pin mlx, mlx-metal and mlx-lm to their latest PyPI releases in nix/mlx-versions.nix."""

import base64
import json
import sys
import urllib.request
from pathlib import Path

PYTHON_VERSION = "3.14"
SYSTEM = "aarch64-darwin"
DIST = "cp314"
MACOS_VARIANT = "26"
PLATFORM = f"macosx_{MACOS_VARIANT}_0_arm64"

OUTPUT = Path(__file__).resolve().parent.parent / "nix" / "mlx-versions.nix"


class BumpError(Exception):
    pass


def fetch_release(name: str) -> dict:
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/json", timeout=30) as resp:
        return json.load(resp)


def sri_from_hex(hex_digest: str) -> str:
    return "sha256-" + base64.b64encode(bytes.fromhex(hex_digest)).decode("ascii")


def find_file(release: dict, filename: str) -> str:
    for entry in release["urls"]:
        if entry["filename"] == filename:
            return sri_from_hex(entry["digests"]["sha256"])
    raise BumpError(f"{filename} not found on PyPI")


def render(version: str, mlx_hash: str, metal_hash: str, lm_version: str, lm_hash: str) -> str:
    return f"""# Generated by scripts/bump_mlx.py. Do not edit by hand.
{{
  version = "{version}";

  mlx = {{
    "{PYTHON_VERSION}-{SYSTEM}" = {{
      platform = "{PLATFORM}";
      dist = "{DIST}";
      hash = "{mlx_hash}";
    }};
  }};

  mlx-metal = {{
    "{MACOS_VARIANT}" = {{
      platform = "{PLATFORM}";
      hash = "{metal_hash}";
    }};
  }};

  mlx-lm = {{
    version = "{lm_version}";
    hash = "{lm_hash}";
  }};
}}
"""


def main() -> int:
    try:
        mlx = fetch_release("mlx")
        metal = fetch_release("mlx-metal")
        lm = fetch_release("mlx-lm")

        version = mlx["info"]["version"]
        metal_version = metal["info"]["version"]
        if version != metal_version:
            raise BumpError(f"mlx {version} and mlx-metal {metal_version} differ")
        lm_version = lm["info"]["version"]

        mlx_hash = find_file(mlx, f"mlx-{version}-{DIST}-{DIST}-{PLATFORM}.whl")
        metal_hash = find_file(metal, f"mlx_metal-{version}-py3-none-{PLATFORM}.whl")
        lm_hash = find_file(lm, f"mlx_lm-{lm_version}.tar.gz")
    except BumpError as err:
        print(f"bump_mlx: {err}", file=sys.stderr)
        return 1

    OUTPUT.write_text(render(version, mlx_hash, metal_hash, lm_version, lm_hash))
    print(f"mlx {version}, mlx-metal {version}, mlx-lm {lm_version} -> {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
